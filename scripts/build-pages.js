#!/usr/bin/env node
// Builds the pre-rendered, search-engine-indexable copies of the content
// pages listed in DATA.pages (data/checklist-data.json):
//   resources → faq/index.html      about → story/index.html
//   countries → from/index.html     plus one from/<slug>/index.html per
//   country with a slug (DATA.countryPages)
// in every language (English unprefixed, others under <lang>/, plus a
// <lang>/index.html home page each), and sitemap.xml listing all of them.
//
// Each one is index.html (same header, footer, scripts and ?v= numbers)
// with its own language, <title>/description/canonical/hreflang/share tags
// and shell text, plus the page's content already inside <main>, captured by letting the real app
// render it in a real browser — so it can never drift from what the app
// itself shows. js/app.js takes over on load as usual (and translates it).
//
// Re-run after changing index.html, the FAQ/glossary/sources/story text,
// countries / countryDetails / checklistItems, or those pages' renderers:
//   node scripts/build-pages.js
// tests/static-pages.test.js fails if the committed files are out of date.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SITE = 'https://port.dog/';
const MARK = '<!-- GENERATED by scripts/build-pages.js from index.html — do not edit by hand. -->';

function escAttr(s) {
  return String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}
function escText(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}
function replaceOnce(html, re, to, what) {
  let n = 0;
  const out = html.replace(re, (...m) => { n++; return typeof to === 'function' ? to(...m) : to; });
  if (n !== 1) throw new Error('build-pages: expected exactly one ' + what + ' in index.html, found ' + n);
  return out;
}

const I18N = require('../js/i18n.js');
const LANGS = I18N.LANGS.map((l) => l.code); // 'en' first
const prefix = (lang) => (lang === 'en' ? '' : lang + '/');
const htmlLang = (lang) => (lang === 'zh' ? 'zh-Hans' : lang);

// Every generated page: each base page (DATA.pages, plus one guide per
// country, DATA.countryPages) in every language — English at /<path>,
// others at /<lang>/<path> — plus each non-English home page (/<lang>/).
// The English home page is index.html itself.
function loadPages() {
  const data = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/checklist-data.json'), 'utf8'));
  const base = Object.keys(data.pages || {}).filter((k) => k[0] !== '_').map((route) => ({ route, basePath: data.pages[route].path }));
  const cp = data.countryPages;
  if (cp) data.countries.filter((c) => c.slug).forEach((c) => base.push({ route: 'country/' + c.code, basePath: cp.pathPrefix + c.slug + '/' }));
  const pages = [];
  LANGS.forEach((lang) => {
    if (lang !== 'en') pages.push({ lang, route: 'home', basePath: '' });
    base.forEach((b) => pages.push(Object.assign({ lang }, b)));
  });
  pages.forEach((p) => {
    p.path = prefix(p.lang) + p.basePath; // e.g. "ja/faq/"
    p.out = path.join(p.path, 'index.html');
  });
  return pages;
}

// Every indexable URL: the home page plus every generated page.
function sitemapXml(pages) {
  return '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<!-- GENERATED by scripts/build-pages.js — do not edit by hand. The wizard and\n' +
    '     checklist (#/ routes) share the home page URL. Each page lists its\n' +
    '     other-language versions itself (hreflang). -->\n' +
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
    ['', ...pages.map((p) => p.path)].map((p) => '  <url><loc>' + SITE + p + '</loc></url>\n').join('') +
    '</urlset>\n';
}

function hreflangBlock(basePath) {
  return '<!-- hreflang: every language version of this page (generated pages get their own). -->\n' +
    LANGS.map((l) => '<link rel="alternate" hreflang="' + htmlLang(l) + '" href="' + SITE + prefix(l) + basePath + '">\n').join('') +
    '<link rel="alternate" hreflang="x-default" href="' + SITE + basePath + '">\n' +
    '<!-- /hreflang -->';
}

// The page shell: index.html with this page's language, metadata, shell
// text and content. `cap` is what the real app rendered (see capture()).
function pageHtml(template, page, cap) {
  const url = SITE + page.path;
  let h = template;
  h = replaceOnce(h, /<!DOCTYPE html>\n/i, (m) => m + MARK + '\n', 'doctype');
  h = replaceOnce(h, /<html lang="en">/, '<html lang="' + htmlLang(page.lang) + '" data-page-lang="' + page.lang + '">', '<html lang="en">');
  // Every relative URL (css/, js/, assets/, data/…, and #/wizard links)
  // must resolve from the site root, not from /ja/faq/.
  h = replaceOnce(h, /<meta charset="UTF-8">\n/, (m) => m + '<base href="/">\n', 'charset meta');
  h = replaceOnce(h, /<title>[^<]*<\/title>/, '<title>' + escText(cap.title) + '</title>', '<title>');
  h = replaceOnce(h, /(<meta name="description" content=")[^"]*(">)/, (m, a, b) => a + escAttr(cap.description) + b, 'meta description');
  h = replaceOnce(h, /(<link rel="canonical" href=")[^"]*(">)/, (m, a, b) => a + url + b, 'canonical');
  h = replaceOnce(h, /<!-- hreflang:[\s\S]*?<!-- \/hreflang -->/, hreflangBlock(page.basePath), 'hreflang block');
  h = replaceOnce(h, /(<meta property="og:url" content=")[^"]*(">)/, (m, a, b) => a + url + b, 'og:url');
  h = replaceOnce(h, /(<meta property="og:title" content=")[^"]*(">)/, (m, a, b) => a + escAttr(cap.title) + b, 'og:title');
  h = replaceOnce(h, /(<meta property="og:description" content=")[^"]*(">)/, (m, a, b) => a + escAttr(cap.description) + b, 'og:description');
  // Site-wide structured data and the no-JS summary belong to the English home page only.
  h = replaceOnce(h, /<script type="application\/ld\+json">[\s\S]*?<\/script>\n/, '', 'JSON-LD block');
  h = replaceOnce(h, /<!-- Shown only without JavaScript[\s\S]*?<\/noscript>\n/, '', 'noscript block');
  // Shell text and links in this page's language, as the app sets them.
  h = h.replace(/href="[^"]*"( data-page-path="([^"]*)")/g, (m, attr, p) => 'href="' + prefix(page.lang) + p + '"' + attr);
  h = h.replace(/(<(\w+)\b[^>]*\bdata-i18n="([^"]+)"[^>]*>)([\s\S]*?)(<\/\2>)/g, (m, open, tag, key, inner, close) =>
    open + (cap.i18n && cap.i18n[key] !== undefined ? cap.i18n[key] : inner) + close);
  h = h.replace(/<\w+\b[^>]*\bdata-i18n-aria="([^"]+)"[^>]*>/g, (open, key) => {
    const v = cap.aria && cap.aria[key];
    if (v === undefined) return open;
    return open.replace(/aria-label="[^"]*"/, 'aria-label="' + escAttr(v) + '"').replace(/title="[^"]*"/, 'title="' + escAttr(v) + '"');
  });
  if (cap.langBtn) {
    h = replaceOnce(h, /(<img class="lang-flag" id="langFlag" src=")[^"]*(")/, (m, a, b) => a + cap.langBtn.flag + b, 'language flag');
    h = replaceOnce(h, /(<span class="lang-code" id="langCode">)[^<]*(<\/span>)/, (m, a, b) => a + cap.langBtn.code + b, 'language code');
    h = replaceOnce(h, /(<button class="lang-btn" id="langBtn"[^>]*aria-label=")[^"]*("[^>]*title=")[^"]*(")/, (m, a, b, c) => a + escAttr(cap.langBtn.label) + b + escAttr(cap.langBtn.title) + c, 'language button');
  }
  h = replaceOnce(h, /<main id="app" class="wrap"><\/main>/,
    '<main id="app" class="wrap" data-prerendered>\n' + (cap.content || '') + '\n</main>', 'empty <main>');
  return h;
}

// What the real app shows for a page once it has rendered it.
async function capture(p) {
  await p.waitForSelector('main#app:not([data-prerendered]) h1');
  return p.evaluate(() => {
    const i18n = {}; const aria = {};
    document.querySelectorAll('[data-i18n]').forEach((n) => { i18n[n.getAttribute('data-i18n')] = n.innerHTML; });
    document.querySelectorAll('[data-i18n-aria]').forEach((n) => { aria[n.getAttribute('data-i18n-aria')] = n.getAttribute('aria-label'); });
    const btn = document.getElementById('langBtn');
    return {
      title: document.title,
      description: document.querySelector('meta[name="description"]').getAttribute('content'),
      content: document.getElementById('app').innerHTML.trim(),
      i18n, aria,
      langBtn: { flag: document.getElementById('langFlag').getAttribute('src'), code: document.getElementById('langCode').textContent, label: btn.getAttribute('aria-label'), title: btn.getAttribute('title') },
    };
  });
}

// Renders every page in a real browser against a server at `base` and
// returns [{out, html}]. Missing output files get a content-less shell
// first so there's something to load. Each language renders in its own
// browser context (its URL prefix sets the language cookie), several
// languages at a time.
async function buildPages(browser, base, { writeShells = false, parallel = 5 } = {}) {
  const template = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  const pages = loadPages();
  const html = {};
  for (const page of pages) {
    const file = path.join(ROOT, page.out);
    if (fs.existsSync(file)) continue;
    if (!writeShells) throw new Error(page.out + ' does not exist — run: node scripts/build-pages.js');
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, pageHtml(template, page, { title: 'port.dog', description: '' }));
  }
  const queue = LANGS.slice();
  async function worker() {
    for (let lang = queue.shift(); lang; lang = queue.shift()) {
      const context = await browser.newContext({ viewport: { width: 1280, height: 900 } }); // fresh: no cookies, light theme
      const p = await context.newPage();
      for (const page of pages.filter((x) => x.lang === lang)) {
        await p.goto(base + '/' + page.path);
        const cap = await capture(p);
        if (new URL(p.url()).pathname !== '/' + page.path) throw new Error(page.path + ' redirected to ' + p.url());
        html[page.out] = pageHtml(template, page, cap);
      }
      await context.close();
    }
  }
  await Promise.all(Array.from({ length: parallel }, worker));
  const results = pages.map((page) => ({ out: page.out, html: html[page.out] }));
  results.push({ out: 'sitemap.xml', html: sitemapXml(pages) });
  return results;
}

module.exports = { buildPages, loadPages, sitemapXml, LANGS };

if (require.main === module) {
  const { chromium } = require('playwright');
  const { startServer, BASE } = require('../tests/helpers');
  (async () => {
    await startServer();
    const browser = await chromium.launch();
    try {
      for (const r of await buildPages(browser, BASE, { writeShells: true })) {
        fs.writeFileSync(path.join(ROOT, r.out), r.html);
        console.log('wrote', r.out);
      }
    } finally {
      await browser.close();
    }
    process.exit(0);
  })().catch((e) => { console.error(e); process.exit(1); });
}
